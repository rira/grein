fn is_pascal_case_type(word: &str) -> bool {
    let bytes = word.as_bytes();
    bytes.len() >= 2
        && bytes[0].is_ascii_uppercase()
        && bytes.iter().any(u8::is_ascii_lowercase)
        && !bytes.contains(&b'_')
}

